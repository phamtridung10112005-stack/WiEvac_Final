"""Offline LOCO ladder. Does not train a firmware model unless real rows exist.

--synthetic-benchmark never overwrites tiny_ai_model_weights.h.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pi" / "app"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from evaluate_loco import pack_blob, refit_selected, run_ladder  # noqa: E402

HEADER_PATH = ROOT / "firmware" / "receiver" / "main" / "tiny_ai_model_weights.h"
META_PATH = ROOT / "firmware" / "receiver" / "main" / "tiny_ai_model_weights.json"


def synthetic_corpus(seed: int = 1) -> dict[str, dict[str, list[list[float]]]]:
    """Empty rows share one latent factor. Occupied rows are independent.

    Marginal variance matches, so univariate MAD misses the sign break that
    Mahalanobis sees.
    """
    rng = random.Random(seed)
    corpus = {}
    for corridor in range(1, 5):
        shift = [rng.uniform(-0.15, 0.15) for _ in range(42)]
        empty = []
        occupied = []
        for _ in range(40):
            factor = rng.gauss(0.0, 1.0)
            empty.append([shift[index] + factor + rng.gauss(0.0, 0.05) for index in range(42)])
        for _ in range(20):
            occupied.append([shift[index] + rng.gauss(0.0, 1.0) for index in range(42)])
        corpus[f"corridor-{corridor:02d}"] = {"empty": empty, "occupied": occupied}
    return corpus


def load_datasets(root: Path) -> dict[str, dict[str, list[list[float]]]]:
    corpus: dict[str, dict[str, list[list[float]]]] = {}
    for path in sorted(root.glob("corridor_*/*.jsonl.gz")):
        label = None
        corridor = None
        rows = []
        with gzip.open(path, "rt", encoding="utf-8") as handle:
            for line in handle:
                record = json.loads(line)
                if record.get("type") == "session":
                    corridor = str(record["corridor_id"])
                    label = str(record["session_label"])
                elif record.get("type") == "feature" and record.get("complete"):
                    rows.append([float(value) for value in record["features"]])
        if corridor is None or label not in {"EMPTY", "OCCUPIED_VAL"} or not rows:
            continue
        bucket = corpus.setdefault(corridor, {"empty": [], "occupied": []})
        key = "empty" if label == "EMPTY" else "occupied"
        bucket[key].extend(rows)
    return corpus


def write_artifact(model: dict, header_path: Path, meta_path: Path, ladder: dict) -> str:
    blob = pack_blob(model)
    digest = hashlib.sha256(blob).hexdigest()
    version = f"tiny-ai-rung{model['rung']}-v1"
    body = []
    for start in range(0, len(blob), 12):
        chunk = ", ".join(f"0x{byte:02x}" for byte in blob[start:start + 12])
        body.append(f"    {chunk},")
    header = "\n".join([
        "#ifndef WIEVAC_TINY_AI_MODEL_WEIGHTS_H",
        "#define WIEVAC_TINY_AI_MODEL_WEIGHTS_H",
        "/* Generated by pi/training/train_tiny_ai.py. Not field-verified. */",
        "#define TINY_AI_MODEL_PRESENT 1",
        f"#define TINY_AI_MODEL_RUNG {model['rung']}",
        f'#define TINY_AI_MODEL_VERSION "{version}"',
        f'#define TINY_AI_MODEL_HASH "{digest}"',
        f"static const unsigned tiny_ai_weight_blob_len = {len(blob)}U;",
        "static const unsigned char tiny_ai_weight_blob[] = {",
        *body,
        "};",
        "#endif /* WIEVAC_TINY_AI_MODEL_WEIGHTS_H */",
        "",
    ])
    header_path.write_text(header, encoding="utf-8")
    meta = {
        "present": True,
        "rung": model["rung"],
        "version": version,
        "feature_schema": "dyn-42-v1",
        "sha256": digest,
        "threshold": model["threshold"],
        "loco_selected": ladder["selected"],
        "corridors": ladder["corridors"],
        "note": "Empty-class novelty only. IMPLEMENTED_PENDING_FIELD_TEST. AI may only lower a score or block rebase.",
    }
    meta_path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    return digest


def _print_ladder(ladder: dict) -> None:
    print("LOCO ladder")
    for rung in range(4):
        tpr01 = sum(ladder["tpr01"][rung]) / len(ladder["tpr01"][rung])
        tpr05 = []
        auroc = []
        for fold in ladder["folds"]:
            tpr05.append(fold[rung]["tpr05"])
            if fold[rung]["auroc"] is not None:
                auroc.append(fold[rung]["auroc"])
        mean05 = sum(tpr05) / len(tpr05)
        mean_auc = sum(auroc) / len(auroc) if auroc else float("nan")
        print(f"rung {rung} tpr@1%={tpr01:.3f} tpr@5%={mean05:.3f} auroc={mean_auc:.3f}")
    print(f"selected {ladder['selected']}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train the empty-corridor novelty ladder.")
    parser.add_argument("--dataset-root", type=Path, default=ROOT / "data" / "datasets")
    parser.add_argument("--synthetic-benchmark", action="store_true")
    parser.add_argument("--export-dir", type=Path)
    args = parser.parse_args(argv)
    if args.synthetic_benchmark:
        corpus = synthetic_corpus()
    else:
        corpus = load_datasets(args.dataset_root)
        if len([name for name, bucket in corpus.items() if bucket["empty"] and bucket["occupied"]]) < 2:
            print("no LOCO dataset yet; firmware stays NOT_READY", file=sys.stderr)
            return 2
    ladder = run_ladder(corpus)
    _print_ladder(ladder)
    if ladder["selected"] <= 0:
        print("export skipped (MAD z-score remains the gate)")
        return 0
    model = refit_selected(corpus, ladder["selected"])
    if model is None:
        print("export skipped (refit failed)")
        return 2
    if args.synthetic_benchmark and args.export_dir is None:
        print("export skipped (synthetic does not replace firmware NOT_READY weights)")
        return 0
    if args.export_dir is not None:
        args.export_dir.mkdir(parents=True, exist_ok=True)
        header = args.export_dir / "tiny_ai_model_weights.h"
        meta = args.export_dir / "tiny_ai_model_weights.json"
    else:
        header, meta = HEADER_PATH, META_PATH
    digest = write_artifact(model, header, meta, ladder)
    print(f"wrote {header} sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
